#!/usr/bin/env python3
"""Writes windows/LazyPDF.Core/Text/BidiTables.cs and its Swift twin Sources/LazyPDFKit/Text/BidiTables.swift
(Bidi_Class, Bidi_Paired_Bracket and Bidi_Mirroring_Glyph tables) and the curated conformance fixture Tests/Fixtures/golden/bidi/bidi-character.txt from the Unicode
Character Database.

  gen_bidi.py [ucd-dir]

ucd-dir holds DerivedBidiClass.txt, BidiBrackets.txt, BidiMirroring.txt and BidiCharacterTest.txt. Without
it the files of VERSION are downloaded from unicode.org into a temporary folder.
"""
import os
import re
import sys
import tempfile
import urllib.request

VERSION = "17.0.0"
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TYPES = ["L", "R", "AL", "EN", "ES", "ET", "AN", "CS", "NSM", "BN", "B", "S", "WS", "ON",
         "LRE", "LRO", "RLE", "RLO", "PDF", "LRI", "RLI", "FSI", "PDI"]
LONG = {"Left_To_Right": "L", "Right_To_Left": "R", "Arabic_Letter": "AL", "European_Terminator": "ET"}
FILES = {
    "DerivedBidiClass.txt": "ucd/extracted/DerivedBidiClass.txt",
    "BidiBrackets.txt": "ucd/BidiBrackets.txt",
    "BidiMirroring.txt": "ucd/BidiMirroring.txt",
    "BidiCharacterTest.txt": "ucd/BidiCharacterTest.txt",
}
MAX_LINES = 400


def fetch(folder):
    for name, path in FILES.items():
        target = os.path.join(folder, name)
        if not os.path.exists(target):
            urllib.request.urlretrieve(f"https://www.unicode.org/Public/{VERSION}/{path}", target)


def read(folder, name):
    with open(os.path.join(folder, name), encoding="utf-8") as f:
        return f.read().split("\n")


def bidi_classes(folder):
    table = [0] * 0x110000
    explicit = []
    for line in read(folder, "DerivedBidiClass.txt"):
        m = re.match(r"# @missing: ([0-9A-F]+)\.\.([0-9A-F]+); (\w+)", line)
        if m:
            lo, hi = int(m[1], 16), int(m[2], 16)
            table[lo:hi + 1] = [TYPES.index(LONG[m[3]])] * (hi - lo + 1)
            continue
        line = line.split("#")[0].strip()
        if line:
            explicit.append(line)
    for line in explicit:
        rng, name = [p.strip() for p in line.split(";")]
        lo, _, hi = rng.partition("..")
        lo = int(lo, 16)
        hi = int(hi, 16) if hi else lo
        table[lo:hi + 1] = [TYPES.index(name)] * (hi - lo + 1)
    return table


def ranges(table):
    out = []
    start = 0
    for cp in range(1, 0x110001):
        if cp == 0x110000 or table[cp] != table[start]:
            out.append(start << 5 | table[start])
            start = cp
    return out


def rows(values, per_line):
    lines = []
    for i in range(0, len(values), per_line):
        lines.append("        " + ", ".join(str(v) for v in values[i:i + per_line]) + ",")
    return "\n".join(lines)


def write_tables(folder, table):
    brackets = []
    for line in read(folder, "BidiBrackets.txt"):
        line = line.split("#")[0].strip()
        if line:
            cp, pair, kind = [p.strip() for p in line.split(";")]
            if kind in ("o", "c"):
                brackets += [int(cp, 16), int(pair, 16), 1 if kind == "o" else 2]
    trip = sorted(zip(brackets[0::3], brackets[1::3], brackets[2::3]))
    brackets = [v for t in trip for v in t]
    mirrors = []
    for line in read(folder, "BidiMirroring.txt"):
        line = line.split("#")[0].strip()
        if line:
            cp, mirror = [int(p.strip(), 16) for p in line.split(";")]
            mirrors += [cp, mirror]
    pairs = sorted(zip(mirrors[0::2], mirrors[1::2]))
    mirrors = [v for p in pairs for v in p]
    text = f"""// Generated by scripts/gen_bidi.py from the Unicode Character Database {VERSION}; do not edit.
// Data files (c) 1991-2025 Unicode, Inc., under the Unicode License v3 (see THIRD-PARTY-NOTICES.txt).
namespace LazyPDF.Core;

internal static partial class BidiData
{{
    // start << 5 | BidiType, one entry per run of code points with the same Bidi_Class.
    private static readonly int[] Ranges =
    [
{rows(ranges(table), 12)}
    ];

    // Code point, its paired bracket, 1 for an opening and 2 for a closing bracket; sorted by code point.
    private static readonly int[] Brackets =
    [
{rows(brackets, 12)}
    ];

    // Code point, Bidi_Mirroring_Glyph; sorted by code point.
    private static readonly int[] Mirrors =
    [
{rows(mirrors, 12)}
    ];
}}
"""
    path = os.path.join(ROOT, "windows", "LazyPDF.Core", "Text", "BidiTables.cs")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)

    swift = f"""// Generated by scripts/gen_bidi.py from the Unicode Character Database {VERSION}; do not edit.
// Data files (c) 1991-2025 Unicode, Inc., under the Unicode License v3 (see THIRD-PARTY-NOTICES.txt).

extension BidiData {{
    // start << 5 | BidiType, one entry per run of code points with the same Bidi_Class.
    static let ranges: [Int32] = [
{rows(ranges(table), 12)}
    ]

    // Code point, its paired bracket, 1 for an opening and 2 for a closing bracket; sorted by code point.
    static let brackets: [Int32] = [
{rows(brackets, 12)}
    ]

    // Code point, Bidi_Mirroring_Glyph; sorted by code point.
    static let mirrors: [Int32] = [
{rows(mirrors, 12)}
    ]
}}
"""
    path = os.path.join(ROOT, "Sources", "LazyPDFKit", "Text", "BidiTables.swift")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(swift)


def curate(folder, table):
    """Keeps the examples that open the file, then adds lines greedily while they bring a new rule trigger:
    a class, a class pair, a paragraph direction with a level, an explicit formatting character at some depth."""
    cases = []
    for line in read(folder, "BidiCharacterTest.txt"):
        if line and not line.startswith("#"):
            cases.append(line)
    seen = set()
    chosen = []

    def features(line):
        cps = [int(c, 16) for c in line.split(";")[0].split()]
        cls = [TYPES[table[c]] for c in cps]
        feats = {("c", c) for c in cls}
        feats |= {("p", a, b) for a, b in zip(cls, cls[1:])}
        feats |= {("t", a, b, c) for a, b, c in zip(cls, cls[1:], cls[2:]) if "NSM" in (a, b, c) or "ET" in (a, b, c) or "CS" in (a, b, c) or "ES" in (a, b, c)}
        fields = line.split(";")
        feats.add(("d", fields[1], fields[2]))
        feats.add(("m", max((int(x) for x in fields[3].split() if x != "x"), default=0)))
        feats |= {("b", c) for c in cps if table[c] == 13 and 0x28 <= c <= 0x5D or c in (0x2329, 0x232A, 0x3008, 0x3009)}
        feats.add(("n", min(len(cps), 12)))
        return feats

    for line in cases[:48]:
        chosen.append(line)
        seen |= features(line)
    rest = [(features(l), l) for l in cases[48:]]
    while len(chosen) < MAX_LINES:
        best, gain = None, 0
        for feats, line in rest:
            g = len(feats - seen)
            if g > gain or (g == gain and best is not None and g and len(line) < len(best[1])):
                best, gain = (feats, line), g
        if best is None or gain == 0:
            break
        chosen.append(best[1])
        seen |= best[0]
        rest.remove(best)
    stride = max(1, len(rest) // 200)
    chosen += [l for _, l in rest[::stride]][:200]
    header = f"""# Curated lines of BidiCharacterTest-{VERSION}.txt (c) 2025 Unicode, Inc., Unicode License v3.
# Fields: code points; paragraph direction (0 LTR, 1 RTL, 2 auto); paragraph level; levels; visual order.
# Written by scripts/gen_bidi.py: the examples that open the original file, then lines that each add a
# class pair, a bracket case or a depth the earlier ones lacked, then a spread over the rest.
"""
    path = os.path.join(ROOT, "Tests", "Fixtures", "golden", "bidi", "bidi-character.txt")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(header + "\n".join(chosen) + "\n")
    print(len(chosen), "lines")


def main():
    folder = sys.argv[1] if len(sys.argv) > 1 else tempfile.mkdtemp()
    if len(sys.argv) <= 1:
        fetch(folder)
    table = bidi_classes(folder)
    write_tables(folder, table)
    curate(folder, table)


main()
